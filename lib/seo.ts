import type { Metadata } from "next";
import { defaultLocale, locales, localeTags, type Locale } from "@/i18n/locales";
import {
  faqs as allFaqs,
  formatAddress,
  getSiteUrl,
  siteConfig,
  t,
  type Faq,
  type Product,
} from "@/lib/site-config";

/** Absolute URL for a locale and a path such as "/products". */
export function localeUrl(locale: string, path = ""): string {
  return `${getSiteUrl()}/${locale}${path === "/" ? "" : path}`;
}

/** hreflang map for a path: every locale plus x-default. */
export function languageAlternates(path = ""): Record<string, string> {
  const languages: Record<string, string> = {};
  for (const locale of locales) languages[localeTags[locale]] = localeUrl(locale, path);
  languages["x-default"] = localeUrl(defaultLocale, path);
  return languages;
}

interface PageMeta {
  locale: string;
  /** Path without the locale prefix, e.g. "/about". Use "" for the home page. */
  path?: string;
  /** Page title. Omit on the home page to use "Brand | Tagline". */
  title?: string;
  /** Falls back to siteConfig.description. */
  description?: string;
  type?: "website" | "article";
  /** Set to false for pages that should not be indexed. */
  index?: boolean;
}

/** Shared metadata helper: localized defaults from site-config, canonical URL and hreflang. */
export function buildMetadata({
  locale,
  path = "",
  title,
  description,
  type = "website",
  index = true,
}: PageMeta): Metadata {
  const brand = t(siteConfig.brandName, locale);
  const desc = description ?? t(siteConfig.description, locale);
  const fullTitle = title ? `${title} | ${brand}` : `${brand} | ${t(siteConfig.tagline, locale)}`;
  const url = localeUrl(locale, path);
  // Generated by app/[locale]/opengraph-image.tsx. Set explicitly because a page-level
  // `openGraph` object replaces the one inherited from the layout.
  const image = {
    url: `${getSiteUrl()}/${locale}/opengraph-image`,
    width: 1200,
    height: 630,
    alt: fullTitle,
  };

  return {
    title: { absolute: fullTitle },
    description: desc,
    alternates: { canonical: url, languages: languageAlternates(path) },
    robots: index ? undefined : { index: false, follow: true },
    openGraph: {
      type,
      url,
      siteName: brand,
      title: fullTitle,
      description: desc,
      locale: localeTags[locale as Locale]?.replace("-", "_"),
      alternateLocale: locales
        .filter((l) => l !== locale)
        .map((l) => localeTags[l].replace("-", "_")),
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description: desc,
      images: [image.url],
    },
  };
}

/* ----------------------------- JSON-LD builders ----------------------------- */

const sameAs = () => Object.values(siteConfig.social).filter((url) => url && url !== "#");

function postalAddress(locale: string) {
  const a = siteConfig.address;
  return {
    "@type": "PostalAddress",
    streetAddress: `${t(a.line1, locale)}, ${t(a.line2, locale)}`,
    addressLocality: t(a.city, locale),
    addressRegion: t(a.state, locale),
    postalCode: a.pincode,
    addressCountry: "IN",
  };
}

export function organizationJsonLd(locale: string) {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    "@id": `${getSiteUrl()}/#organization`,
    name: t(siteConfig.brandName, locale),
    description: t(siteConfig.description, locale),
    url: localeUrl(locale),
    logo: `${getSiteUrl()}/icon.svg`,
    foundingDate: String(siteConfig.establishedYear),
    email: siteConfig.emails.info,
    telephone: siteConfig.phone,
    address: postalAddress(locale),
    sameAs: sameAs(),
    contactPoint: {
      "@type": "ContactPoint",
      contactType: "sales",
      telephone: siteConfig.phone,
      email: siteConfig.emails.sales,
      availableLanguage: ["English", "Hindi", "Gujarati"],
    },
  };
}

export function localBusinessJsonLd(locale: string) {
  return {
    "@context": "https://schema.org",
    "@type": "LocalBusiness",
    "@id": `${getSiteUrl()}/#localbusiness`,
    name: t(siteConfig.brandName, locale),
    description: t(siteConfig.description, locale),
    url: localeUrl(locale),
    image: `${getSiteUrl()}/${locale}/opengraph-image`,
    telephone: siteConfig.phone,
    email: siteConfig.emails.info,
    address: postalAddress(locale),
    openingHours: t(siteConfig.businessHours, locale),
    parentOrganization: { "@id": `${getSiteUrl()}/#organization` },
  };
}

export function productJsonLd(product: Product, locale: string) {
  return {
    "@context": "https://schema.org",
    "@type": "Product",
    name: t(product.name, locale),
    description: t(product.shortDescription, locale),
    image: product.images.map((img) => `${getSiteUrl()}${img.src}`),
    url: localeUrl(locale, `/products/${product.slug}`),
    category: "Groundnut oil",
    brand: { "@type": "Brand", name: t(siteConfig.brandName, locale) },
    manufacturer: { "@id": `${getSiteUrl()}/#organization` },
  };
}

export function faqJsonLd(locale: string, items: Faq[] = allFaqs) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    inLanguage: localeTags[locale as Locale],
    mainEntity: items.map((faq) => ({
      "@type": "Question",
      name: t(faq.question, locale),
      acceptedAnswer: { "@type": "Answer", text: t(faq.answer, locale) },
    })),
  };
}

export function breadcrumbJsonLd(locale: string, items: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: localeUrl(locale, item.path),
    })),
  };
}

